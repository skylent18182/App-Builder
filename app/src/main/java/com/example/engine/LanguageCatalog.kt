    private val EXTENSION_MAP: Map<String, LanguageInfo> by lazy {
        val map = mutableMapOf<String, LanguageInfo>()
        for (lang in ALL_LANGUAGES) {
            for (ext in lang.extensions) {
                map[ext.lowercase()] = lang
            }
        }
        map
    }

    val FALLBACK_LANGUAGE = LanguageInfo("text", "Text / Asset", "Generic Text", listOf(".txt"), "#9CA3AF", false)

    fun detectLanguage(filePath: String, sampleContent: String = ""): LanguageInfo {
        val lower = filePath.lowercase()
        val fileName = lower.substringAfterLast("/")
        
        // Exact filename matching
        if (fileName == "dockerfile" || fileName.startsWith("dockerfile.")) return EXTENSION_MAP[".dockerfile"] ?: FALLBACK_LANGUAGE
        if (fileName == "makefile" || fileName == "gnumakefile") return EXTENSION_MAP[".mk"] ?: FALLBACK_LANGUAGE
        if (fileName == "cmakelists.txt") return EXTENSION_MAP[".cmake"] ?: FALLBACK_LANGUAGE
        if (fileName.startsWith(".env")) return EXTENSION_MAP[".env"] ?: FALLBACK_LANGUAGE
        if (fileName == "cargo.toml") return EXTENSION_MAP["cargo.toml"] ?: EXTENSION_MAP[".toml"] ?: FALLBACK_LANGUAGE

        // Multi-part extension matching (e.g. .gradle.kts, .d.ts)
        if (lower.endsWith(".gradle.kts")) return EXTENSION_MAP[".gradle.kts"] ?: EXTENSION_MAP[".kt"] ?: FALLBACK_LANGUAGE
        if (lower.endsWith(".d.ts")) return EXTENSION_MAP[".d.ts"] ?: EXTENSION_MAP[".ts"] ?: FALLBACK_LANGUAGE
        if (lower.endsWith(".html.erb")) return EXTENSION_MAP[".html.erb"] ?: FALLBACK_LANGUAGE

        val ext = if (fileName.contains(".")) "." + fileName.substringAfterLast(".") else ""
        val matched = EXTENSION_MAP[ext]
        if (matched != null) return matched

        // Content heuristic
        if (sampleContent.startsWith("#!")) {
            val firstLine = sampleContent.substringBefore("\n")
            if (firstLine.contains("python")) return EXTENSION_MAP[".py"] ?: FALLBACK_LANGUAGE
            if (firstLine.contains("bash")) return EXTENSION_MAP[".bash"] ?: FALLBACK_LANGUAGE
            if (firstLine.contains("sh")) return EXTENSION_MAP[".sh"] ?: FALLBACK_LANGUAGE
            if (firstLine.contains("node")) return EXTENSION_MAP[".js"] ?: FALLBACK_LANGUAGE
            if (firstLine.contains("ruby")) return EXTENSION_MAP[".rb"] ?: FALLBACK_LANGUAGE
        }

        return FALLBACK_LANGUAGE
    }

    fun isSupportedLanguageFile(filePath: String): Boolean {
        val lower = filePath.lowercase()
        val fileName = lower.substringAfterLast("/")
        val ext = if (fileName.contains(".")) "." + fileName.substringAfterLast(".") else ""
        return EXTENSION_MAP.containsKey(ext) ||
               fileName == "dockerfile" ||
               fileName == "makefile" ||
               fileName == "cmakelists.txt" ||
               fileName.startsWith(".env")
    }

    fun isTextFile(filePath: String, sampleBytes: ByteArray? = null): Boolean {
        if (isSupportedLanguageFile(filePath)) return true
        val lower = filePath.lowercase()
        if (lower.endsWith(".xml") || lower.endsWith(".json") || lower.endsWith(".md") ||
            lower.endsWith(".txt") || lower.endsWith(".properties") || lower.endsWith(".gradle") ||
            lower.endsWith(".kts") || lower.endsWith(".kt") || lower.endsWith(".java")) return true
        if (sampleBytes != null && sampleBytes.isNotEmpty()) {
            val checkLen = minOf(sampleBytes.size, 512)
            for (i in 0 until checkLen) {
                if (sampleBytes[i] == 0.toByte()) return false
            }
            return true
        }
        return false
    }

    fun analyzeProjectLanguages(project: AndroidProject): List<ProjectLanguageStat> {
        val langCounts = mutableMapOf<LanguageInfo, Pair<Int, Int>>()
        var totalFileCount = 0
        
        for ((path, content) in project.files) {
            val lang = detectLanguage(path, content)
            val lines = content.lines().size
            val curr = langCounts.getOrDefault(lang, Pair(0, 0))
            langCounts[lang] = Pair(curr.first + 1, curr.second + lines)
            totalFileCount++
        }

        return langCounts.map { (lang, counts) ->
            val pct = if (totalFileCount > 0) (counts.first.toFloat() / totalFileCount) * 100f else 0f
            ProjectLanguageStat(lang, counts.first, counts.second, pct)
        }.sortedByDescending { it.fileCount }
    }

    fun extractMarkdownDocs(project: AndroidProject): List<MarkdownDocInfo> {
        val docs = mutableListOf<MarkdownDocInfo>()
        for ((path, content) in project.files) {
            val lower = path.lowercase()
            if (lower.endsWith(".md") || lower.endsWith(".markdown") || lower.endsWith(".mdown") ||
                lower.endsWith(".mkdn") || lower.contains("readme") || lower.contains("changelog")) {
                val fileName = path.substringAfterLast("/")
                val lines = content.lines()
                val title = lines.find { it.trimStart().startsWith("# ") }?.removePrefix("#")?.trim()
                    ?: fileName.substringBeforeLast(".")
                val words = content.split("\\s+".toRegex()).filter { it.isNotBlank() }.size
                docs.add(MarkdownDocInfo(path, fileName, content, lines.size, words, title))
            }
        }
        return docs.sortedBy { it.path }
    }
